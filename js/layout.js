/* Items/children only navigate once they carry an `href` (i.e. a real page
   exists for them). Everything else keeps the normal look and stays
   clickable, but shows an "under development" toast instead of navigating. */
function sidebarItemHtml(item, activePage, basePath) {
  const active = item.key === activePage ? ' active' : '';
  const badge = item.badge ? `<span class="sb-badge">${item.badge}</span>` : '';
  const inner = `${item.icon}\n            <span>${item.label}</span>\n            ${badge}`;

  if (item.href) {
    return `
        <div class="sb-item-wrapper">
          <a class="sb-item${active}" href="${basePath}${item.href}">
            ${inner}
          </a>
        </div>`;
  }
  return `
        <div class="sb-item-wrapper">
          <div class="sb-item${active}" onclick="showUnderDevelopmentToast()">
            ${inner}
          </div>
        </div>`;
}

function sidebarGroupHtml(group, activePage, basePath) {
  const isActiveGroup = group.children.some(c => c.key === activePage);
  const expanded = isActiveGroup ? ' expanded' : '';
  const children = group.children.map(c => {
    const active = c.key === activePage ? ' active' : '';
    if (c.href) {
      return `
          <div class="sb-child-wrapper">
            <div class="sb-leaf"><div class="sb-divider"></div></div>
            <a class="sb-child${active}" href="${basePath}${c.href}"><span>${c.label}</span></a>
          </div>`;
    }
    return `
          <div class="sb-child-wrapper">
            <div class="sb-leaf"><div class="sb-divider"></div></div>
            <div class="sb-child${active}" onclick="showUnderDevelopmentToast()"><span>${c.label}</span></div>
          </div>`;
  }).join('');

  return `
        <div class="sb-nav-group${expanded}" id="sbGroup${group.groupKey.charAt(0).toUpperCase() + group.groupKey.slice(1)}">
        <div class="sb-item-wrapper">
          <div class="sb-item sb-parent" onclick="toggleSbGroup(this)">
            ${group.icon}
            <span>${group.label}</span>
            <svg class="sb-chevron" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.5"><path d="M4 6l4 4 4-4"/></svg>
          </div>
        </div>
        <div class="sb-children">${children}
        </div>
        </div>`;
}

function sidebarHtml(activePage, basePath) {
  const sections = SIDEBAR_SECTIONS.map(section => {
    const heading = section.heading
      ? `\n        <div class="sb-group-header">\n          ${section.heading}\n        </div>`
      : '';
    const items = (section.items || []).map(item => sidebarItemHtml(item, activePage, basePath)).join('');
    const groups = (section.groups || []).map(group => sidebarGroupHtml(group, activePage, basePath)).join('');
    return `\n      <div class="sb-section">${heading}${items}${groups}\n      </div>`;
  }).join('');

  return sections;
}

function renderLayout(activePage, basePath) {
  basePath = basePath || '';
  window.ASSET_BASE = basePath;
  document.getElementById('navbar-root').innerHTML = navbarHtml(basePath);
  const sidebarRoot = document.getElementById('sidebar-root');
  sidebarRoot.className = 'sidebar';
  sidebarRoot.innerHTML = sidebarHtml(activePage, basePath);

  if (!document.getElementById('sbToast')) {
    document.body.insertAdjacentHTML('beforeend', '<div class="toast" id="sbToast">This feature is under development</div>');
  }
}
