    <tr>
      <td>${i + 1}.</td>
      <td>
        <span class="lb-model-cell">
          <span class="lb-model-icon" style="background:${m.bg}">${getLogoHtml(m)}</span>
          ${m.name}
        </span>
      </td>
      <td class="lb-num">${fmt(m.tokens)}</td>
    </tr>
